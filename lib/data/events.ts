export type EventStatus = "open" | "limited" | "invite";
export type EventKind = "promo" | "championship";

export interface CalendarEvent {
  id: string;
  date: string; // ISO YYYY-MM-DD
  /** Дата окончания (для акций/конкурсов с периодом действия). */
  endDate?: string;
  /** Тип спец-события: акция или конкурс. */
  kind?: EventKind;
  /** CTA-метка для акций/конкурсов. */
  ctaLabel?: string;
  /** ID градиента (см. src/lib/promo.ts PROMO_STYLES). По умолчанию выбирается по kind. */
  promoStyle?: string;
  city: string;
  cityKz?: string;
  title: string;
  titleKz?: string;
  brands: string[];
  status: EventStatus;
  note: string;
  noteKz?: string;
  description: string;
  descriptionKz?: string;
  time?: string;
  // IMPROVED: тематические изображения событий (ссылка + alt для доступности)
  imageUrl?: string;
  imageAlt?: string;
  // NEW: фотогалерея с самого события (для слайдера в модалке)
  gallery?: { src: string; alt?: string }[];
  // NEW: место проведения (адрес)
  venue?: string;
}

// IMPROVED: подбор тематической картинки по типу события (бренд / формат)
// Используются безопасные стоковые изображения Unsplash с фиксированными параметрами.
function pickEventImage(e: Omit<CalendarEvent, "imageUrl" | "imageAlt">): {
  imageUrl: string;
  imageAlt: string;
} {
  const t = `${e.title} ${e.brands.join(" ")} ${e.note}`.toLowerCase();
  // ELEKTROFORUM / большие форумы — конференц-сцена
  if (t.includes("elektroforum") || t.includes("форум") || t.includes("слёт")) {
    return {
      imageUrl:
        "https://images.unsplash.com/photo-1505373877841-8d25f7d46678?auto=format&fit=crop&w=1200&q=70",
      imageAlt: "Конференция ELEKTROFORUM — сцена и аудитория",
    };
  }
  // Чемпионат — соревнование, инструмент
  if (t.includes("чемпионат") || t.includes("соревнован")) {
    return {
      imageUrl:
        "https://images.unsplash.com/photo-1581094288338-2314dddb7ece?auto=format&fit=crop&w=1200&q=70",
      imageAlt: "Чемпионат по электромонтажу — работа с инструментом",
    };
  }
  // Legrand / щиты
  if (t.includes("legrand") || t.includes("щит") || t.includes("автомат")) {
    return {
      imageUrl:
        "https://images.unsplash.com/photo-1620283085439-39620a1e21c4?auto=format&fit=crop&w=1200&q=70",
      imageAlt: "Электрический щит и автоматические выключатели",
    };
  }
  // IEK / автоматика и шкафы
  if (t.includes("iek") || t.includes("шкаф")) {
    return {
      imageUrl:
        "https://images.unsplash.com/photo-1558449907-8b8cd2c2c0d9?auto=format&fit=crop&w=1200&q=70",
      imageAlt: "Промышленная автоматика и шкафы",
    };
  }
  // CHINT / промышленная электрика
  if (t.includes("chint") || t.includes("промышл")) {
    return {
      imageUrl:
        "https://images.unsplash.com/photo-1581092580497-e0d23cbdf1dc?auto=format&fit=crop&w=1200&q=70",
      imageAlt: "Промышленное электрооборудование",
    };
  }
  // Вебинар / онлайн
  if (t.includes("вебинар") || t.includes("онлайн") || t.includes("online")) {
    return {
      imageUrl:
        "https://images.unsplash.com/photo-1587620962725-abab7fe55159?auto=format&fit=crop&w=1200&q=70",
      imageAlt: "Онлайн-вебинар на ноутбуке",
    };
  }
  // Мастер-класс / тренинг / воркшоп
  if (
    t.includes("мастер-класс") ||
    t.includes("masterclass") ||
    t.includes("тренинг") ||
    t.includes("training") ||
    t.includes("воркшоп") ||
    t.includes("workshop") ||
    t.includes("интенсив") ||
    t.includes("лекц")
  ) {
    return {
      imageUrl:
        "https://images.unsplash.com/photo-1573164713988-8665fc963095?auto=format&fit=crop&w=1200&q=70",
      imageAlt: "Семинар и обучение специалистов",
    };
  }
  // Roadshow / тур / встреча
  if (t.includes("tour") || t.includes("тур") || t.includes("roadshow") || t.includes("встреч")) {
    return {
      imageUrl:
        "https://images.unsplash.com/photo-1556761175-5973dc0f32e7?auto=format&fit=crop&w=1200&q=70",
      imageAlt: "Деловая встреча специалистов",
    };
  }
  // По умолчанию — нейтральное «электрическое» изображение
  return {
    imageUrl:
      "https://images.unsplash.com/photo-1473341304170-971dccb5ac1e?auto=format&fit=crop&w=1200&q=70",
    imageAlt: "Электрика и инфраструктура",
  };
}

