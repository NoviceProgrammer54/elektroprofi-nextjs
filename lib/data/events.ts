// IMPROVED: автоматически дополняем каждое событие тематической картинкой, если она не задана вручную
export const events: CalendarEvent[] = [...eventsRaw]
  .map((e) => {
    if (e.imageUrl) return e;
    const pic = pickEventImage(e);
    return { ...e, imageUrl: pic.imageUrl, imageAlt: e.imageAlt ?? pic.imageAlt };
  })
  .sort((a, b) => a.date.localeCompare(b.date));

export const eventCities = Array.from(new Set(events.map((e) => e.city))).sort();

// UPDATED v1.2: список месяцев, в которых есть события — для фильтра календаря
export interface MonthOption {
  key: string; // "2026-04"
  year: number;
  month: number; // 0-11
}
export const eventMonths: MonthOption[] = Array.from(
  new Map<string, MonthOption>(
    events.map((e) => {
      const d = new Date(e.date);
      const key = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`;
      return [key, { key, year: d.getFullYear(), month: d.getMonth() }];
    }),
  ).values(),
).sort((a, b) => a.key.localeCompare(b.key));