/** Все электрики указанного города */
export function expertsByCity(cityId: string): Expert[] {
  return experts.filter((e) => e.cityId === cityId);
}

/** Найти электрика по id (slug) */
export function expertById(id: string): Expert | undefined {
  return experts.find((e) => e.id === id);
}

/** Полное имя в формате «Имя Фамилия» */
export function fullName(e: Pick<Expert, "firstName" | "lastName">): string {
  return `${e.firstName} ${e.lastName}`;
}

/** Сгруппировать всех электриков по городам: { [cityId]: Expert[] } */
export function expertsGroupedByCity(): Record<string, Expert[]> {
  return experts.reduce<Record<string, Expert[]>>((acc, expert) => {
    (acc[expert.cityId] ||= []).push(expert);
    return acc;
  }, {});
}


