/** Полная карточка электрика */
export interface Expert {
  // --- Идентификация ---
  id: string;              // уникальный slug, напр. "aidos-kozhan"
  firstName: string;       // ИМЯ
  lastName: string;        // ФАМИЛИЯ
  cityId: string;          // id города из `src/data/cities.ts`
  status: ExpertStatus;    // см. ExpertStatus выше
  role?: ExpertRole;       // должность в команде (если есть)
  skillLevel?: ExpertSkillLevel; // уровень мастерства (если присвоен)

  // --- Краткая инфа (показывается на карточке) ---
  specialization: string;  // короткая строка-бейдж
  description: string;     // короткий текст до раскрытия
  experienceYears?: number;

  // --- Подробный профиль (показывается в модалке «Подробнее») ---
  experience?: string;        // напр. «в электромонтаже с 2012 года»
  education?: string;         // образование
  permitGroup?: string;       // группа допуска, напр. «III группа»
  skills?: string[];          // профессиональные навыки
  preferredWorkMain?: string[];   // основные предпочтительные работы
  preferredWorkExtra?: string[];  // дополнительные работы
  paymentMethods?: string[];      // способы оплаты
  instagram?: string;             // @username
  interests?: string;             // профессиональные интересы
  hobbies?: string;               // хобби
  shortBio?: string;              // «о себе» — длинный текст в модалке

  // --- Медиа ---
  photoUrl?: string | null;       // импортированный ассет или URL
  permitDocumentUrl?: string | null; // PDF/изображение удостоверения о группе допуска
  educationDocumentUrl?: string | null; // PDF/изображение документа об образовании (диплом)
}


